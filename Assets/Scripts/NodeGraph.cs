using System.Collections;
using System.Collections.Generic;
using System.Linq;
using Unity.Mathematics;
using Unity.VisualScripting;
using UnityEngine;
using UnityEngine.Rendering;
using static NodeGraphShaderManager;

public class NodeGraph
{
    #region Inputted data. All the other lists of nodes and links are pulled from this data and/or generated internally.
    /// <summary>
    /// The cards in this nodegraph. This is one of the two things that other objects add to this node graph.
    /// </summary>
    List<Card> cards = new();
    /// <summary>
    /// The buffer that tracks all pin links that were added to the graph.
    /// </summary>
    Dictionary<ulong, (Card, Card)> pendingPinLinks = new();
    #endregion

    NodeGraphShaderManager shaderManager = new();

    /// <summary>
    /// Marks whether this NodeGraph has been built yet or not.
    /// </summary>
    private bool built;
    public bool IsReady
    {
        get
        {
            return built;
        }
    }

    #region Data buffers that require building
    /// <summary>
    /// All the dynamic links between pins generated by the node graph, indexed by a unique ID value generated from a given pair of Card objects.
    /// These links are the ones that can be culled by the compute shader if they intersect with each other, or the cardLinks.
    /// </summary>
    Dictionary<ulong, NodeLink> pinLinks = new();
    /// <summary>
    /// A buffer that collects and stores the nodes. The nodegraph should never need to generate its own nodes.
    /// </summary>
    List<Node> nodesBuffer = new();
    /// <summary>
    /// Nodes generated after a pathfinder is ran to create new routes for subsequent pathfinders
    /// </summary>
    List<Node> newPathNodes = new();
    /// <summary>
    /// A collection of all the static links generated by the cards. None of these should be generated by nodegraph.
    /// </summary>
    List<NodeLink> cardLinks = new();
    /// <summary>
    /// Invalid static links used purely for collision testing. These should not be considered links that pathways can use.
    /// </summary>
    List<NodeLink> invalidCardLinks = new();
    /// <summary>
    /// Links generated between nodes on different cards. These are not considered when checking for collisions, as they're just for pathfinding.
    /// However, they will have their collisions checked against just the cardLinks, and will destroy themselves if they collide with any of the card links.
    /// </summary>
    List<NodeLink> intercardLinks = new();
    /// <summary>
    /// This will store all the routes that the strings between the pins will take.
    /// </summary>
    Dictionary<ulong, PathFramework> pinRoutes = new();
    #endregion

    #region Functions that allow inputting data into the graph
    /// <summary>
    /// Adds a given card object to this node graph
    /// </summary>
    public void AddCard(Card target)
    {
        cards.Add(target);
        built = false;
    }
    /// <summary>
    /// <para>Creates a link between two cards. This will ultimately put 1 pin on each of the cards, and create string between them.</para>
    /// <para>The order of the cards is irrelevant.</para>
    /// </summary>
    /// <param name="a">One of the cards that will be linked. The order is irrelevant.</param>
    /// <param name="b">The other card that will be linked. The order is irrelevant.</param>
    public void AddLink(Card a, Card b)
    {
        //Add the links on each of the cards (so they can generate the necessary pin nodes)
        a.AddLink(b);
        b.AddLink(a);

        //Add an entry to the pending links list so they can be generated when built
        pendingPinLinks.Add(Card.GetCardPairID(a, b), (a, b));

        built = false;
    }
    /// <summary>
    /// <para>Removes a link between cards.</para>
    /// <para>The order of the cards is irrelevant.</para>
    /// </summary>
    /// <param name="a">One of the cards that will be linked. The order is irrelevant.</param>
    /// <param name="b">The other card that will be linked. The order is irrelevant.</param>
    public void RemoveLink(Card a, Card b)
    {
        a.RemoveLink(b);
        b.RemoveLink(a);

        ulong code = Card.GetCardPairID(a, b);

        pendingPinLinks.Remove(code);

        built = false;
    }
    public void Clear()
    {
        cards.Clear();
        pinLinks.Clear();
        pendingPinLinks.Clear();
        newPathNodes.Clear();
        ClearBufferedData();
        built = false;
    }
    #endregion

    #region Building-related logic
    /// <summary>
    /// Tracks if the graph is already building itself, used to prevent the Build coroutine from running more than one at a time.
    /// </summary>
    private bool building;
    void ClearBufferedData()
    {
        nodesBuffer.Clear();
        pinRoutes.Clear();
        static void ClearLinkList(List<NodeLink> target)
        {
            for (int i = target.Count - 1; i >= 0; i--)
            {
                target[i].Release();
            }
            target.Clear();
        }
        ClearLinkList(cardLinks);
        ClearLinkList(invalidCardLinks);
        ClearLinkList(intercardLinks);
    }
    /// <summary>
    /// Builds the graph using the data. This needs to be ran every time a change is made to the graph.
    /// </summary>
    /// <returns></returns>
    public IEnumerator Build()
    {
        if (building || built) yield break;
        building = true;

        ClearBufferedData();

        //Buffer nodes and links from the cards
        foreach (Card card in cards)
        {
            nodesBuffer.AddRange(card.CornerNodes);
            nodesBuffer.AddRange(card.PinNodes);
            cardLinks.AddRange(card.ValidCornerLinks);
            invalidCardLinks.AddRange(card.InvalidCornerLinks);
        }

        //Generates the the pin links, now that all the nodes are in their "final" spots (before needing to rebuild again)
        foreach (ulong pair in pendingPinLinks.Keys)
        {
            pinLinks.Add(pair, new NodeLink(
                pendingPinLinks[pair].Item1.GetLinkingNode(pendingPinLinks[pair].Item2), //Get the node on the "from" card that represents the pin that will be connected to "to"
                pendingPinLinks[pair].Item2.GetLinkingNode(pendingPinLinks[pair].Item1), //Get the node on the "to" card that represents the pin that will be connected to "from"
                false //Mark this link as an invalid pathway for pathfinding
                ));
        }

        //Generate a bunch of links between nodes
        for (int a = 0; a < nodesBuffer.Count; a++)
        {
            //Initialising b to a will ensure we're only evaluating pairs that haven't been evaluated yet
            for (int b = a; b < nodesBuffer.Count; b++)
            {
                //If at least one of them are not a pin
                if (!(nodesBuffer[a].isPin && nodesBuffer[b].isPin))
                {
                    //If they originate from different cards
                    if (nodesBuffer[a].card != nodesBuffer[b].card)
                    {
                        intercardLinks.Add(new NodeLink(nodesBuffer[a], nodesBuffer[b], true));
                    }
                }
            }
        }

        //Use compute shaders to cull intersecting links, and calculate their lengths.
        List<NodeLink> staticLinks = new List<NodeLink>(cardLinks.Count + invalidCardLinks.Count);
        staticLinks.AddRange(cardLinks);
        staticLinks.AddRange(invalidCardLinks);
        yield return shaderManager.DoSDCheckAndAssignLengths(staticLinks, intercardLinks, true);

        //yield return ProcessPinLinks();

        building = false;
        built = true;
    }
    #endregion

    /// <summary>
    /// Initially, all pin-to-pin links are just direct paths from one side to the other.
    /// We need to check if these initial paths are creating intersections, and cull the ones that are, to be replaced with one that we use pathfinding algorithms to generate.
    /// </summary>
    /// <returns></returns>
    public IEnumerator ProcessPinLinks(PathfinderManager pathfinderManager)
    {
        //First, we check if the pins are intersecting with any walls using the same GPU-accelerated approach we used with the other nodes.
        List<NodeLink> pinList = pinLinks.Values.ToList();

        //Cull the pin links that intersect with card edges
        yield return shaderManager.DoSDCheck(cardLinks, pinList, true);

        //Cull the least possible pin links so that no pin links intersect with each other 
        yield return shaderManager.DoDChecks(pinList);

        //QUICK AND DIRTY REMOVE METHOD -- TO BE REWRITTEN AFTER THE WHOLE SYSTEM WORKS
        ulong[] pinLinkKeys = pinLinks.Keys.ToArray();
        for (int i = pinLinkKeys.Length - 1; i >= 0; i--)
        {
            ulong key = pinLinkKeys[i];
            if (pinList.Contains(pinLinks[key]))
            {
                //We just use pinLinks[key].start because which end of the route is the start and the end is entirely arbritrary and doesn't matter
                pinRoutes.Add(key, new SingleLinkPath(new PointedNodeLink(pinLinks[key], pinLinks[key].start)));
            }
        }

        //Remove all intercard links that intersect with the remaining pin links
        yield return shaderManager.DoSDCheck(pinList, intercardLinks, false);

        //We now enter a loop:
        //We branch, and use pathfinding to find the best path for each pin-to-pin link we no longer have.
        //Using an analysis algorithm, we will pick which path to go with.
        //We will then remove the links that path used from the list of available links.
        //For the pins that we removed, we will also generate new nodes and links around them, by expanding the shape of the cards and using some other simple algorithms
        //This loop will break once there are no longer any missing pin-to-pin links.

        List<(NodeLink, ulong)> linksToRepair = new();

        //QUICK AND DIRTY METHOD FOR GETTING THE DESTROYED PIN LINKS -- TO BE REWRITTEN AFTER THE WHOLE SYSTEM WORKS
        //If I do not have time to replace this I am going to be extremely upset
        for (int i = pinLinks.Keys.Count - 1; i >= 0; i--)
        {
            ulong key = pinLinks.Keys.ToArray()[i];
            if (!pinList.Contains(pinLinks[key]))
            {
                linksToRepair.Add((pinLinks[key], key));
            }
        }

        //Sort the list of links needed to be repaired by distance, I'm pretty sure it's doing the highest distance ones first (which I'm pretty sure ends up being the best way to do it)
        linksToRepair.OrderBy(link => link.Item1.distance);

        while (linksToRepair.Count > 0)
        {
            //Repair the first link in the list
            Pathfinder repair = pathfinderManager.CreatePathfinder(linksToRepair[0].Item1.start, linksToRepair[0].Item1.end);
            yield return repair;

            //Add the route
            pinRoutes.Add(linksToRepair[0].Item2, repair.Result);

            //Remove the old broken link from the list of links that need repair
            linksToRepair.RemoveAt(0);

            //Get a list of NodeLinks representing the best path that the pathfinder found
            List<NodeLink> repairResultLinks = repair.Result.ToNodeLinkList();

            //Remove all the node links that this path used from the intercard link index
            for (int i = 0; i < repairResultLinks.Count; i++)
            {
                //We only need to worry about releasing the links for the pathfinder.
                //The lists of intercard links stored in this NodeGraph are not important at this point, so we won't worry about culling them.
                //The performance impact of searching through the entire list and removing each NodeLink is far greater than the, like, 10 extra GPU threads they create otherwise.
                repairResultLinks[i].Release();
            }

            //Destroy the intercard links that intersect with this new route
            yield return shaderManager.DoSDCheck(repairResultLinks, intercardLinks, false);

            //Generate new nodes, strategically placed in spots that would allow new paths to run adjacent to the runs that this path used
            List<Node> newNodes = repair.Result.GenerateAdjacentNodes();
            List<NodeLink> newLinks = new();
            //Generate intercard links between the new nodes and the existing ones
            for (int a = 0; a < newNodes.Count; a++)
            {
                for (int b = 0; b < nodesBuffer.Count; b++)
                {
                    //If they originate from different cards
                    if (newNodes[a].card != nodesBuffer[b].card)
                    {
                        newLinks.Add(new NodeLink(newNodes[a], nodesBuffer[b], true));
                    }
                }
            }
            //Still gotta do the new nodes against each other
            for (int a = 0; a < newNodes.Count; a++)
            {
                //Initialising b to a will ensure we're only evaluating pairs that haven't been evaluated yet
                for (int b = a + 1; b < newNodes.Count; b++)
                {
                    newLinks.Add(new NodeLink(newNodes[a], newNodes[b], true));
                }
            }
            //Use compute shaders to cull intersecting links, and calculate their lengths.
            List<NodeLink> staticLinks = new(cardLinks.Count + invalidCardLinks.Count);
            staticLinks.AddRange(cardLinks);
            staticLinks.AddRange(invalidCardLinks);
            foreach (PathFramework path in pinRoutes.Values)
            {
                staticLinks.AddRange(path.ToNodeLinkList());
            }
            yield return shaderManager.DoSDCheckAndAssignLengths(staticLinks, newLinks, false);

            newPathNodes.AddRange(newNodes);

            yield return new WaitForSeconds(2);

            //Add the new links to the intercardLink list
            intercardLinks.AddRange(newLinks);

            yield return new WaitForSeconds(2);
        }
    }

    #region Debug functions that will be removed
    //Everything with "debug" in front of it is temporary and will be removed before the end of the project
    public void DebugRender(Vector3 offset, bool renderCards, bool renderPins, bool renderIntercards, NavPath[] withPaths)
    {
        if (renderIntercards)
        {
            foreach (NodeLink intercardLink in intercardLinks)
            {
                Debug.DrawLine(intercardLink.StartPos + offset, intercardLink.EndPos + offset, Color.Lerp(Color.green, Color.red, intercardLink.distance / 14f));
            }
        }
        if (renderCards)
        {
            foreach (NodeLink cardLink in cardLinks)
            {
                Debug.DrawLine(cardLink.StartPos + offset, cardLink.EndPos + offset, Color.blue);
            }
        }
        if (renderPins)
        {
            foreach (NodeLink pinLink in pinLinks.Values)
            {
                Debug.DrawLine(pinLink.StartPos + offset, pinLink.EndPos + offset, Color.cyan);
            }
        }
        if (withPaths != null)
        {
            foreach (PathFramework path in withPaths)
            {
                Node[] nodeArray = path.GetOrderedNodeArray();
                for (int i = 0; i < nodeArray.Length - 1; i++)
                {
                    Debug.DrawLine((Vector3)nodeArray[i].position + offset, (Vector3)nodeArray[i + 1].position + offset, Color.white);
                }
            }
        }
        else
        {
            foreach (PathFramework path in pinRoutes.Values)
            {
                Node[] nodeArray = path.GetOrderedNodeArray();
                for (int i = 0; i < nodeArray.Length - 1; i++)
                {
                    Debug.DrawLine((Vector3)nodeArray[i].position + offset, (Vector3)nodeArray[i + 1].position + offset, Color.white);
                }
            }
        }
    }
#if UNITY_EDITOR
    public void DebugRenderLabels(Vector3 offset)
    {
        foreach (Node node in nodesBuffer)
        {
            node.Debug_DrawID(offset);
        }
        foreach (Node node in newPathNodes)
        {
            node.Debug_DrawID(offset);
        }
    }
