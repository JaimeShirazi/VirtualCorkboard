/// <summary>
/// A small container for NodeLink that specifies which node is the start and which node is the end
/// </summary>
public struct PointedNodeLink
{
    private NodeLink link;
    private bool isInverted;
    public NodeLink Link
    {
        get
        {
            return link;
        }
    }
    public Node Start
    {
        get
        {
            return isInverted ? link.start: link.end;
        }
    }
    public Node End
    {
        get
        {
            return isInverted ? link.end: link.start;
        }
    }
    public PointedNodeLink(NodeLink link, Node origin)
    {
        this.link = link;
        isInverted = !link.IsOrigin(origin);
    }
}
/// <summary>
/// Once Paths have been constructed, their links cannot be modified. New paths objects are created in their place, these paths being generated by said paths.
/// </summary>
public class Path : IHavePriority
{
    private float cost;
    private void CalculateCost(float heuristic)
    {
        cost = path[0].Link.distance;
        for (int i = 1; i < path.Length; i++)
        {
            cost += path[i].Link.distance;
        }
        cost += heuristic;
    }
    public float Priority
    {
        get
        {
            return cost;
        }
    }
    readonly Node endNode;
    readonly Node targetNode;
    readonly PointedNodeLink[] path;
    public Path(Node fromNode, Node toNode)
    {
        endNode = fromNode;
        targetNode = toNode;
        path = new PointedNodeLink[0];
    }
    private Path(Path existingPath, PointedNodeLink nextLink)
    {
        targetNode = existingPath.targetNode;
        path = new PointedNodeLink[existingPath.path.Length + 1];
        existingPath.path.CopyTo(path, 0);
        path[^1] = nextLink;
        endNode = nextLink.End;
    }
    public PathRequest Split()
    {
        List<NodeLink> availableLinks = endNode.Links.ToList();
        Path[] newPaths = new Path[endNode.Links.Length - (path.Length > 0 ? 1 : 0)];
        NativeArray<float> positions = new NativeArray<float>(newPaths.Length * 2 + 2, Allocator.TempJob);
        //First 2 entries are the same, just the x and y of the end points
        positions[0] = targetNode.position.x;
        positions[1] = targetNode.position.y;
        int nextIndex = 0;
        for (int i = availableLinks.Count - 1; i >= 0; i--)
        {
            if (path.Length > 0)
            {
                //Remove the link from the list that goes back to the node we just came from, if there is any nodes on the path in the first place
                if (availableLinks[i] == path[^1].Link)
                {
                    availableLinks.RemoveAt(i);
                }
            }
            else
            {
                //Add a new path that clones this path's nodes, but adds the link at availableLinks[i] to the end
                PointedNodeLink pointedBuffer = new PointedNodeLink(availableLinks[i], endNode);
                newPaths[nextIndex] = new Path(this, pointedBuffer);
                //Prepare the values for multithreaded processing
                positions[(nextIndex * 2) + 2] = pointedBuffer.End.position.x;
                positions[(nextIndex * 2) + 3] = pointedBuffer.End.position.y;

                nextIndex++;
            }
        }

        NativeArray<float> costs = new NativeArray<float>(newPaths.Length, Allocator.TempJob);

        IJobParallelFor preparedJob = new CalculateHeuristics()
        {
            pos = positions,
            costs = costs
        };

        return new PathRequest()
        {
            job = preparedJob,
            onComplete = () => OnCalculationComplete(costs, newPaths)
        };
    }
    public Path[] OnCalculationComplete(NativeArray<float> costs, Path[] newPaths)
    {
        for (int i = 0; i < costs.Length; i++)
        {
            newPaths[i].CalculateCost(costs[i]);
        }
        return newPaths;
    }
    struct CalculateHeuristics : IJobParallelFor
    {
        [ReadOnly] public NativeArray<float> pos;
        public NativeArray<float> costs;
        public void Execute(int i)
        {
            int index = (i * 2) + 2;
            costs[i] += Mathf.Sqrt(Mathf.Pow(pos[0] - pos[index], 2) + Mathf.Pow(pos[1] - pos[index + 1], 2));
        }
    }
}
public struct PathRequest
{
    public IJobParallelFor job;
    public Func<Path[]> onComplete;
}
