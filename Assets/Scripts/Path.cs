using System;
using System.Collections.Generic;
using System.Linq;
using Unity.Collections;
using Unity.Jobs;
using UnityEngine;

/// <summary>
/// A small container for NodeLink that specifies which node is the start and which node is the end
/// </summary>
public struct PointedNodeLink
{
    private NodeLink link;
    private bool isInverted;
    public NodeLink Link
    {
        get
        {
            return link;
        }
    }
    public Node Start
    {
        get
        {
            return isInverted ? link.end : link.start;
        }
    }
    public Node End
    {
        get
        {
            return isInverted ? link.start : link.end;
        }
    }
    public PointedNodeLink(NodeLink link, Node origin)
    {
        this.link = link;
        isInverted = !link.IsOrigin(origin);
    }
}
/// <summary>
/// Once Paths have been constructed, their links cannot be modified. New paths objects are created in their place, these paths being generated by said paths.
/// </summary>
public class Path
{
    private float cost;
    private void CalculateCost(float heuristic)
    {
        cost = path[0].Link.distance;
        for (int i = 1; i < path.Length; i++)
        {
            cost += path[i].Link.distance;
        }
        cost += heuristic;
    }
    public float Cost
    {
        get
        {
            return cost;
        }
    }
    readonly Node endNode;
#if UNITY_EDITOR
    public Node EndNode
    {
        get
        {
            return endNode;
        }
    }
#endif
    readonly Node targetNode;
    public bool IsComplete
    {
        get
        {
            return endNode == targetNode;
        }
    }
    readonly PointedNodeLink[] path;
    public PointedNodeLink[] Links
    {
        get
        {
            return path;
        }
    }
    /// <summary>
    /// This will always be the initial path creation, so the cost will be entirely heuristic.
    /// </summary>
    public Path(Node fromNode, Node toNode)
    {
        endNode = fromNode;
        targetNode = toNode;
        path = new PointedNodeLink[0];
        cost = Vector2.Distance(fromNode.position, toNode.position); //Since we're only doing this once, it's not a big deal to just calculate it on the main thread
    }
    /// <summary>
    /// This is called when a path is split
    /// </summary>
    /// <param name="existingPath"></param>
    /// <param name="nextLink"></param>
    private Path(Path existingPath, PointedNodeLink nextLink)
    {
        targetNode = existingPath.targetNode;
        path = new PointedNodeLink[existingPath.path.Length + 1];
        existingPath.path.CopyTo(path, 0);
        path[^1] = nextLink;
        endNode = nextLink.End;
    }
    NativeArray<float> costs, positions;
    Path[] pendingSplit;
    public SplitRequest Split()
    {
#if UNITY_EDITOR
        Debug.Log("Splitting " + EndNode.id);
#endif

        List<NodeLink> availableLinks = endNode.Links.ToList();
        pendingSplit = new Path[endNode.Links.Length - (path.Length > 0 ? 1 : 0)];
        positions = new NativeArray<float>(pendingSplit.Length * 2 + 2, Allocator.TempJob);
        //First 2 entries are the same, just the x and y of the end points
        positions[0] = targetNode.position.x;
        positions[1] = targetNode.position.y;
        int nextIndex = 0;
#if UNITY_EDITOR
        Debug.Log("Found " + availableLinks.Count + " links");
#endif
        for (int i = availableLinks.Count - 1; i >= 0; i--)
        {
            if (path.Length > 0)
            {
                //Remove the link from the list that goes back to the node we just came from, if there is any nodes on the path in the first place
                if (availableLinks[i] == path[^1].Link)
                {
                    availableLinks.RemoveAt(i);
                    continue;
                }
            }

            //Add a new path that clones this path's nodes, but adds the link at availableLinks[i] to the end
            PointedNodeLink pointedBuffer = new PointedNodeLink(availableLinks[i], endNode);
            pendingSplit[nextIndex] = new Path(this, pointedBuffer);
            //Prepare the values for multithreaded processing
            positions[(nextIndex * 2) + 2] = pointedBuffer.End.position.x;
            positions[(nextIndex * 2) + 3] = pointedBuffer.End.position.y;

            nextIndex++;

#if UNITY_EDITOR
            Debug.Log("Link from " + pointedBuffer.Link.start.id + " to " + pointedBuffer.Link.end.id);
#endif
        }

        costs = new NativeArray<float>(pendingSplit.Length, Allocator.TempJob);

        CalculateHeuristics preparedJob = new CalculateHeuristics()
        {
            pos = positions,
            costs = costs
        };

        return new SplitRequest()
        {
            job = preparedJob,
            onComplete = () => OnCalculationComplete(),
            threads = pendingSplit.Length
        };
    }
    public struct SplitRequest
    {
        public CalculateHeuristics job;
        public Func<Path[]> onComplete;
        public int threads;
    }
    public Path[] OnCalculationComplete()
    {
        for (int i = 0; i < costs.Length; i++)
        {
#if UNITY_EDITOR
            try
            {
                //TODO: this is returning null for some reason
                Debug.Log("ID: " + pendingSplit[i].EndNode.id);
            }
            catch { }
            try
            {
                Debug.Log("Cost: " + costs[i]);
            }
            catch { }
            Debug.Log("Index " + i + " ends at " + pendingSplit[i].EndNode.id + " with cost " + costs[i]);
#endif
            pendingSplit[i].CalculateCost(costs[i]);
        }
        positions.Dispose();
        costs.Dispose();
        return pendingSplit;
    }
    public struct CalculateHeuristics : IJobParallelFor
    {
        [ReadOnly] public NativeArray<float> pos;
        public NativeArray<float> costs;
        public void Execute(int i)
        {
            int index = (i * 2) + 2;
            costs[i] += Mathf.Sqrt(Mathf.Pow(pos[0] - pos[index], 2) + Mathf.Pow(pos[1] - pos[index + 1], 2));
        }
    }
}