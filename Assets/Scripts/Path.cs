/// <summary>
/// <para>A small container for NodeLink that specifies which node is the start and which node is the end.</para>
/// <para>Technically, NodeLinks already label the nodes as "Start" and "End", but that was out of necessity, and is not actually meant to represent a target direction.</para>
/// <para>All this struct does is determine if the "Start" and "End" nodes in a given link line up with a specified first node, and if not, inverts the order.</para>
/// </summary>
public struct PointedNodeLink
{
    public PointedNodeLink(NodeLink link, Node origin)
    {
        this.link = link;
        isInverted = !link.IsOrigin(origin);
    }
    private NodeLink link;
    private bool isInverted;
    public NodeLink Link
    {
        get
        {
            return link;
        }
    }
    public Node Start
    {
        get
        {
            return isInverted ? link.end : link.start;
        }
    }
    public Node End
    {
        get
        {
            return isInverted ? link.start : link.end;
        }
    }
}
public abstract class PathFramework
{
    /// <summary>
    /// The last node in this path. Cannot be changed after creation. Technically redundant, but allows for paths with 0 links to exist.
    /// </summary>
    public Node EndNode
    {
        get
        {
            return endNode;
        }
    }
    protected readonly Node endNode;

    /// <summary>
    /// The node that this path is aiming to reach. This informs the heuristic calculation when the path is split.
    /// </summary>
    protected readonly Node targetNode;

    /// <summary>
    /// An array of pointed node links representing the path.
    /// </summary>
    protected readonly PointedNodeLink[] path;
    public Node[] GetOrderedNodeArray()
    {
        Node[] nodes = new Node[path.Length + 1];
        for (int i = 0; i < path.Length; i++)
        {
            nodes[i] = path[i].Start;
        }
        nodes[^1] = endNode;
        return nodes;
    }

    protected PathFramework(Node fromNode, Node toNode, int pathSize)
    {
        endNode = fromNode;
        targetNode = toNode;
        path = new PointedNodeLink[pathSize];
    }
}
public class SingleLinkPath : PathFramework
{
    public SingleLinkPath(PointedNodeLink link) : base(link.Start, link.End, 1)
    {
        path[0] = link;
    }
}
/// <summary>
/// Once Paths have been constructed, their links cannot be modified. New paths objects are created in their place, these paths being generated by said paths.
/// </summary>
public class NavPath : PathFramework
{
    #region Cost logic
#if UNITY_EDITOR
    //NOTE: THESE SHOULD NOT BE EXPOSED - DELETE LATER
    public float CostSoFar
    {
        get
        {
            return costSoFar;
        }
    }
    public float CostHeuristic
    {
        get
        {
            return costHeuristic;
        }
    }
#endif

    //Lower = more likely to find best path, will require more processing
    //  - Don't go lower than 1; 1 is garuanteed to find the shortest path as it will always be the shortest possible distance to the goal.
    //Higher = less likely to find the best path, reduce processing load
    const float HEURISTIC_COST_MULTIPLIER = 1f;
    
    /// <summary>
    /// Buffering the cost so far.
    /// </summary>
    private float costSoFar;
    /// <summary>
    /// Buffering the heuristic cost.
    /// </summary>
    private float costHeuristic;
    /// <summary>
    /// The sum of the cost-so-far and estimated future cost
    /// </summary>
    public float Cost
    {
        get
        {
            return costSoFar + costHeuristic;
        }
    }
    /// <summary>
    /// Given a heuristic value representing distance to the goal, will assign the cost to this path. Called by the path that this path split off from.
    /// </summary>
    /// <param name="heuristic"></param>
    private void CalculateCost(float heuristic)
    {
        costSoFar += path[^1].Link.distance; //Since we always copy the cost-so-far from the previous path, all we need to do is add the most recent node's length.
        costHeuristic = heuristic * HEURISTIC_COST_MULTIPLIER;
    }
    #endregion

    /// <summary>
    /// Tracks all the nodes this path has visited. This is so when the path splits, we can quickly check if we have visited a node before.
    /// </summary>
    private HashSet<Node> visitedNodes;

    /// <summary>
    /// Whether the path reaches its target.
    /// </summary>
    public bool IsComplete
    {
        get
        {
            return endNode == targetNode;
        }
    }
    /// <summary>
    /// Whether a path does not lead anywhere.
    /// </summary>
    public bool IsDead
    {
        get
        {
            return (endNode.Links.Length < 1);
        }
    }

    #region Constructors
    /// <summary>
    /// This constructor is called by Pathfinders when a path needs to be first created. All future path constructions will be handled by the paths themselves when they split. As such, this is the only public constructor.
    /// </summary>
    /// <param name="fromNode">The node this path will start at.</param>
    /// <param name="toNode">The node this path wants to reach.</param>
    public NavPath(Node fromNode, Node toNode) : base (fromNode, toNode, 0)
    {
        //There is no cost-so-far for the inital path, so cost is calculated purely based on heuristic. This isn't even technically necessary, but the performance penalty is so negligable, we might as well for the sake of expandability.
        costHeuristic = Vector2.Distance(fromNode.position, toNode.position);
        visitedNodes = new HashSet<Node>
        {
            fromNode,
            toNode
        };
    }
    /// <summary>
    /// A path will call this to construct new paths based on itself, with a new link added to the path.
    /// </summary>
    /// <param name="existingPath">The path to model this one on</param>
    /// <param name="nextLink">The new link to add to the path</param>
    private NavPath(NavPath existingPath, PointedNodeLink nextLink) : base (nextLink.End, existingPath.targetNode, existingPath.path.Length + 1)
    {
        existingPath.path.CopyTo(path, 0);
        path[^1] = nextLink;
        costSoFar = existingPath.costSoFar;
        visitedNodes = new HashSet<Node>(existingPath.visitedNodes)
        {
            nextLink.End
        };
    }
    #endregion

    #region Multithreaded splitting process
    /// <summary>
    /// Tells a Path to create an array of paths that branch 1 step outwards from itself (without going backwards).
    /// The path prepares a parallel Job that will then compute the heuristic cost for each of these new paths.
    /// It also provides a function that will assign these heuristic costs to their respective paths, and return the now-ready paths to be added to the PriorityQueue.
    /// </summary>
    /// <returns>A struct containing a parallel Job that should be scheduled, and function to be called on completion.</returns>
    public SplitRequest Split()
    {
        List<NodeLink> availableLinks = endNode.Links.ToList();
        //Cull all the links that are shouldn't be evaluated
        for (int i = availableLinks.Count - 1; i >= 0; i--)
        {
            if (path.Length > 0)
            {
                //Remove the link from the list that goes back to the node we just came from, if there is any nodes on the path in the first place
                if (availableLinks[i] == path[^1].Link)
                {
                    availableLinks.RemoveAt(i);
                    continue;
                }
            }
            PointedNodeLink directedLink = new PointedNodeLink(availableLinks[i], endNode);
            //Remove links that obstruct other pin nodes that we aren't aiming for
            if (directedLink.End.isPin && directedLink.End != targetNode)
            {
                availableLinks.RemoveAt(i);
                continue;
            }
            //Remove paths that go to a node that this path has already been
            if (visitedNodes.Contains(directedLink.End))
            {
                availableLinks.RemoveAt(i);
                continue;
            }
        }

        //An array of nodes generated, split off from this Path.
        NavPath[] pendingSplit = new NavPath[availableLinks.Count];
        NativeArray<float> positions = new NativeArray<float>(pendingSplit.Length * 2 + 2, Allocator.TempJob);
        //First 2 entries are the same, just the x and y of the end points
        positions[0] = targetNode.position.x;
        positions[1] = targetNode.position.y;
        for (int i = 0; i < availableLinks.Count; i++)
        {
            //Add a new path that clones this path's nodes, but adds the link at availableLinks[i] to the end
            PointedNodeLink pointedBuffer = new PointedNodeLink(availableLinks[i], endNode);
            pendingSplit[i] = new NavPath(this, pointedBuffer);
            //Prepare the values for multithreaded processing
            positions[(i * 2) + 2] = pointedBuffer.End.position.x;
            positions[(i * 2) + 3] = pointedBuffer.End.position.y;
        }

        NativeArray<float> costs = new NativeArray<float>(pendingSplit.Length, Allocator.TempJob);

        CalculateHeuristics preparedJob = new CalculateHeuristics()
        {
            pos = positions,
            costs = costs
        };

        return new SplitRequest()
        {
            job = preparedJob,
            onComplete = () => OnCalculationComplete(pendingSplit, costs, positions),
            threads = pendingSplit.Length
        };
    }
    /// <summary>
    /// A struct containing the data that the Pathfinder will need after telling a Path to split itself.
    /// The job is a parallel Job that the Pathfinder handles scheduling for, and the function should be called when the job completes.
    /// The thread count also informs how many threads the Job needs.
    /// </summary>
    public struct SplitRequest
    {
        public CalculateHeuristics job;
        public Func<NavPath[]> onComplete;
        public int threads;
    }
    /// <summary>
    /// The parallel Job that calculates the heuristic cost for the given array of positions.
    /// pos[0] and pos[1] represent target.x and target.y respectively.
    /// All consecutive values represent the different end node positions for the paths, in their array order.
    /// </summary>
    public struct CalculateHeuristics : IJobParallelFor
    {
        [ReadOnly] public NativeArray<float> pos;
        public NativeArray<float> costs;
        public void Execute(int i)
        {
            int index = (i * 2) + 2;
            costs[i] += Mathf.Sqrt(Mathf.Pow(pos[0] - pos[index], 2) + Mathf.Pow(pos[1] - pos[index + 1], 2));
        }
    }
    /// <summary>
    /// <para>This is a function that is passed to the Pathfinder with all the parameters already assigned to.</para>
    /// <para>It is meant to be called after the parallel job completes, and it reads the results back and assigns the costs to the Paths created earlier.</para>
    /// <para>This is the final step in preparing these Paths. Once the cost is assigned, the function returns the array of paths, as it is now ready to be added to the PriorityQueue.</para>
    /// <para>The paths are not accessible to the pathfinder at any stage until this function returns them.</para>
    /// </summary>
    /// <param name="pendingPaths">The paths yet to have their costs assigned</param>
    /// <param name="costs">The native array with the results of the parallel Job, for assigning and disposing.</param>
    /// <param name="positions">The native array with the position data used by the parallel Job, for disposing.</param>
    /// <returns>The now-ready array of Paths to be added to the PriorityQueue.</returns>
    public NavPath[] OnCalculationComplete(NavPath[] pendingPaths, NativeArray<float> costs, NativeArray<float> positions)
    {
        for (int i = 0; i < costs.Length; i++)
        {
            pendingPaths[i].CalculateCost(costs[i]);
        }
        positions.Dispose();
        costs.Dispose();

        return pendingPaths;
    }
    #endregion
}